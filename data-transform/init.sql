-- ------------------------------------------------------------
-- Composite View: Gia lap ket qua dbt transform gop cac domain
-- ------------------------------------------------------------
CREATE VIEW IF NOT EXISTS city_health_snapshot AS
SELECT
  d.id            AS district_id,
  d.name          AS district_name,
  t.recorded_at   AS recorded_at,
  (100 - t.congestion_index)                       AS traffic_score,
  g.renewable_pct                                  AS energy_score,
  GREATEST(0, 100 - a.aqi)                         AS air_score,
  w.recycled_pct                                   AS waste_score,
  ROUND(
    ((100 - t.congestion_index) + g.renewable_pct + GREATEST(0, 100 - a.aqi) + w.recycled_pct) / 4.0,
    1
  ) AS city_health_index
FROM traffic_flow t
JOIN grid_load g
  ON g.district_id = t.district_id AND g.recorded_at = t.recorded_at
JOIN air_quality a
  ON a.district_id = t.district_id AND a.recorded_at = t.recorded_at
JOIN waste_collection w
  ON w.district_id = t.district_id AND w.recorded_at = t.recorded_at
JOIN districts d
  ON d.id = t.district_id;
